# Unknown characters are drawn as a box
_UNKNOWN = ["###", "#.#", "#.#", "#.#", "###"]


def glyph_pixels(char):
    """The (dx, dy) offsets of the set pixels of a character"""
    rows = _GLYPHS.get(char.upper() if 'a' <= char <= 'z' else char, _UNKNOWN)
    return [(dx, dy) for dy, row in enumerate(rows) for dx, cell in enumerate(row) if cell == '#']


GLYPHS = {char: glyph_pixels(char) for char in _GLYPHS}
UNKNOWN_GLYPH = glyph_pixels('\x00')


def text_pixels(text):
    """Yield (dx, dy) for every set pixel of a text; '\\n' starts a new line"""
    x = y = 0
    for char in text:
        if char == '\n':
            x = 0
            y += ADVANCE_Y
            continue
        if char != ' ':
            for dx, dy in GLYPHS.get(char.upper() if 'a' <= char <= 'z' else char, UNKNOWN_GLYPH):
                yield x + dx, y + dy
        x += ADVANCE_X
